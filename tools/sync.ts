/*
 * Copies shared/src and shared/icons into each browser extension folder and
 * writes that build's browser flag.
 *
 *   bun run tools/sync.ts     (or: make sync)
 *
 * The copies are committed so both folders load without a build step; edit
 * shared/ and re-run this, never the generated folders.
 */
import { cpSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dir, '..');
const SRC = join(ROOT, 'shared', 'src');
const ICONS = join(ROOT, 'shared', 'icons');

for (const browser of ['chrome', 'firefox'] as const) {
  const dest = join(ROOT, browser);
  rmSync(join(dest, 'src'), { recursive: true, force: true });
  rmSync(join(dest, 'icons'), { recursive: true, force: true });
  cpSync(SRC, join(dest, 'src'), { recursive: true });
  cpSync(ICONS, join(dest, 'icons'), { recursive: true });
  writeFileSync(
    join(dest, 'src', 'shared', 'browser.js'),
    `/* generated by make sync — do not edit */\nvar __scrambiliniBrowser = '${browser}';\n`,
  );
  console.log(`synced ${browser}/src and ${browser}/icons`);
}
